/* หาภาคจากชื่อจังหวัด — เผื่อพิมพ์มีคำนำหน้า/ต่อท้าย (เช่น "จ.เชียงใหม่") จะลองจับคู่แบบ substring ให้ด้วย */
function getRegionByProvince(province) {
  if (!province) return null;
  const trimmed = province.trim();
  if (PROVINCE_TO_REGION[trimmed]) return PROVINCE_TO_REGION[trimmed];
  const found = Object.keys(PROVINCE_TO_REGION).find(p => trimmed.includes(p));
  return found ? PROVINCE_TO_REGION[found] : null;
}